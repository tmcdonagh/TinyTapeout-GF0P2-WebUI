"""Regenerate pico/include/index_html.h from the shared data/index.html.

Runs as a PlatformIO pre-script (extra_scripts = pre:scripts/gen_headers.py):
executes before compilation, so the inlined UI always matches the shared
source file. Rewrites the header only when content changes to avoid
needless rebuilds.

Note: PlatformIO executes pre-scripts without __file__, so paths derive
from $PROJECT_DIR (the directory containing this project's platformio.ini).
"""

import os

Import("env")

PROJECT_DIR = env.subst("$PROJECT_DIR")
SRC = os.path.join(PROJECT_DIR, os.pardir, "data", "index.html")
DST = os.path.join(PROJECT_DIR, "include", "index_html.h")


def esc(s: str) -> str:
    # Escape a self-contained slice of raw HTML. Must be called per-slice
    # (never on pre-joined text) so a chunk boundary can never split an
    # escape sequence.
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "")
    )


def main() -> None:
    with open(SRC, encoding="utf-8") as f:
        html = f.read().replace("\r\n", "\n")

    lines = [
        "#pragma once",
        "#include <Arduino.h>",
        "// Generated by scripts/gen_headers.py from data/index.html - do not edit.",
        "const char INDEX_HTML[] PROGMEM =",
    ]
    # Slice the raw HTML, then escape each slice: escapes can never
    # straddle a chunk boundary.
    chunk = 96
    pieces = [html[i:i + chunk] for i in range(0, len(html), chunk)]
    if pieces:
        lines += ['    "{}"'.format(esc(p)) for p in pieces]
        lines[-1] += ";"
    else:
        lines.append('    "";')
    text = "\n".join(lines) + "\n"

    if os.path.exists(DST):
        with open(DST, encoding="utf-8") as f:
            if f.read() == text:
                return
    with open(DST, "w", encoding="utf-8") as f:
        f.write(text)
    print("gen_headers: wrote include/index_html.h (%d bytes html)" % len(html))


main()
